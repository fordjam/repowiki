def test_r4_registered_web_citations_render_like_relative_ones(repo: Path, tmp_path: Path) -> None:
    with_wiki(repo)
    sha = json.loads((repo / "docs/wiki/index.json").read_text())["indexed_commit"]
    hub, mirror = "https://code.example.test/example/widgetry", "https://gitlab.example.test/mirror/widgetry"
    page = repo / "docs/wiki/1-overview.md"
    page.write_text(
        page.read_text()
        + f"\n\nPinned [cli.py:2-3]({hub}/blob/{sha}/src/widgetry/cli.py#L2-L3), "
        f"mirror [cli.py:4]({mirror}/-/blob/{sha}/src/widgetry/cli.py#L4) and "
        f"foreign [FOREIGN](https://code.example.test/other/widgetry/blob/{sha}/x.py#L1).\n"
    )
    cfg = tmp_path / "repos.json"
    cfg.write_text(json.dumps({"repos": [{"name": "W", "path": str(repo), "url": hub, "aliases": [mirror]}]}))
    out = tmp_path / "site"
    build_site(load_repos(cfg), out, log=lambda _m: None, now=NOW)
    html = (out / "w/1-overview.html").read_text()
    # Both pinned forms become citation chips pointing at the indexed commit on the canonical host.
    assert f'href="{hub}/blob/{sha}/src/widgetry/cli.py?plain=1#L2-L3"' in html
    assert f'href="{hub}/blob/{sha}/src/widgetry/cli.py?plain=1#L4"' in html
    assert html.count('<span class="cite-file">src/widgetry/cli.py</span>') >= 2
    # A foreign link stays an ordinary link.
    assert 'href="https://code.example.test/other/widgetry/' in html
    # R6: an unpinned source URL or a raw HTML anchor at source is a validation error, so a wiki holding
    # one is never rendered (before R6 they were rendered as text); the last good site stays in place.
    good = html
    for bad in (f"[UNPINNED]({hub}/blob/main/src/widgetry/cli.py#L5)", '<a href="../../src/widgetry/cli.py#L6">x</a>'):
        page.write_text(page.read_text() + f"\n\n{bad}\n")
        with pytest.raises(SiteError, match="failed validation"):
            build_site(load_repos(cfg), out, log=lambda _m: None, now=NOW)
        assert (out / "w/1-overview.html").read_text() == good
        page.write_text(page.read_text().replace(f"\n\n{bad}\n", ""))


