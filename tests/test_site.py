def test_a_png_scanline_with_an_unknown_filter_type_is_refused() -> None:
    # Every CRC and the inflated size are right; only the second row's filter byte (255) is impossible.
    def chunk(kind: bytes, body: bytes) -> bytes:
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))

    def png(filters: bytes) -> bytes:
        rows = b"".join(bytes([f]) + b"\x33\x66\xcc" * 2 for f in filters)
        ihdr = struct.pack(">IIBBBBB", 2, len(filters), 8, 2, 0, 0, 0)
        return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(rows)) + chunk(b"IEND", b"")

    assert image_content_defect(png(bytes([0, 1, 2, 3, 4]))) is None  # all five filter types exist
    assert "scanline 2 has filter type 255" in (image_content_defect(png(bytes([0, 255, 0]))) or "")
    assert "filter type 5" in (image_content_defect(png(bytes([5]))) or "")


