    build_site([RepoEntry("W", repo)], out, log=lambda _m: None, now=NOW)
    assert 'href="2-b.html#setup-1"' in (out / "w/1-a.html").read_text()
    target = (out / "w/2-b.html").read_text()
    assert 'id="setup"' in target and 'id="setup-1"' in target


