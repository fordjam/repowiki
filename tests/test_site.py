def test_identical_titles_stay_repo_scoped(repo: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    from conftest import FILES, register, run_git

    with_wiki(repo)
    other = tmp_path / "twin"
    other.mkdir()
    run_git(other, "init", "-q", "-b", "main")
    for rel, content in FILES.items():
        write(other, rel, content)
    commit(other, "initial")
    register(other, monkeypatch)
    with_wiki(other)
    for r in (repo, other):  # both wikis now hold pages that share one title
        index = r / "docs/wiki/index.json"
        data = json.loads(index.read_text())
        for entry in data["pages"]:
            entry["title"] = "Overview"
        index.write_text(json.dumps(data))
    portal = PortalHooks(branding="Acme", logout_action="/logout", token_endpoint="/csrf-token")
    out = tmp_path / "site"
    build_site([RepoEntry("W", repo), RepoEntry("Twin", other)], out, portal=portal, log=lambda _m: None, now=NOW)
    data = json.loads((out / "w/1-overview.html").read_text().split('id="repowiki-search">')[1].split("</template>")[0])
    titles = [e for e in data["pages"] if e["t"] == "Overview"]
    by_repo = {e["r"] for e in titles}
