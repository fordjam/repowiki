"""Filesystem guard rails.

Page writes and deletions stay inside the wiki directory, use plain file names
(never paths), never follow symlinks, and require exact local ownership for existing
pages. Authoritative receipts and transaction evidence live in Git administration.
"""

from __future__ import annotations

import fcntl
import hashlib
import json
import os
import re
import shutil
import stat
import subprocess
import tempfile
import threading
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path

INDEX = "index.json"
PAGE_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*\.md$")
# Written at the end of every generated page for display, never as mutation authority.
GENERATED_MARK = "<!-- generated by repowiki -->"


class UnsafePathError(ValueError):
    """A path would take a read, write or delete outside the wiki directory."""


def safe_page_file(value: object) -> bool:
    return isinstance(value, str) and bool(PAGE_NAME_RE.fullmatch(value))


def check_wiki_dir(wiki_dir: str) -> str:
    """Normalised repo-relative wiki directory; rejects absolute paths, ``..`` and ``.git``."""
    raw = str(wiki_dir).strip()
    if not raw or raw.startswith(("/", "\\", "~")) or re.match(r"^[A-Za-z]:", raw) or "\\" in raw:
        raise UnsafePathError(f"wiki_dir must be a relative path inside the repository, got {wiki_dir!r}")
    parts = [p for p in raw.split("/") if p not in ("", ".")]
    if not parts or ".." in parts:
        raise UnsafePathError(f"wiki_dir must stay inside the repository, got {wiki_dir!r}")
    if parts[0] == ".git":
        raise UnsafePathError("wiki_dir cannot be inside .git")
    return "/".join(parts)


def wiki_path(root: Path, wiki_dir: str) -> Path:
    """``root/wiki_dir``, refusing any symlinked component that leads outside ``root``."""
    rel = check_wiki_dir(wiki_dir)
    path = root / rel
    real_root = root.resolve()
    real = path.resolve()
    if real != real_root and real_root not in real.parents:
        raise UnsafePathError(f"{rel} resolves outside the repository ({real}); refusing to use it")
    if real == real_root:
        raise UnsafePathError(f"{rel} resolves to the repository root; refusing to use it")
    return path


def wiki_file(wiki: Path, name: str) -> Path:
    """A page or index file directly inside ``wiki``; never a symlink or a directory."""
    if name != INDEX and not safe_page_file(name):
        raise UnsafePathError(f"not a plain page file name: {name!r}")
    path = wiki / name
    if path.is_symlink():
        raise UnsafePathError(f"{path} is a symlink; refusing to read or write through it")
    if path.exists() and not path.is_file():
        raise UnsafePathError(f"{path} is not a regular file")
    return path


def read_wiki_file(wiki: Path, name: str) -> str | None:
    path = wiki_file(wiki, name)
    return path.read_text(encoding="utf-8") if path.is_file() else None


def atomic_write(path: Path, text: str) -> None:
    """Write via a temp file in the same directory and ``os.replace`` it into place."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def generated_by_repowiki(path: Path) -> bool:
    """True only for a regular, non-symlink file that carries repowiki's page marker."""
    if path.is_symlink() or not path.is_file():
        return False
    try:
        return GENERATED_MARK in path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False


# --------------------------------------------------------------------------- transactional publish

# The checkout journal of earlier versions. It is never read or acted on: a file in the checkout
# cannot authorize changing or deleting anything.
JOURNAL = ".repowiki-journal.json"
TXN_ROOT = "repowiki-txn"  # in worktree Git administration: <admin>/repowiki-txn/<wiki identity>/
RECORD = "record.json"
STAGE = "stage"
_HEX64 = re.compile(r"^[0-9a-f]{64}$")
MAX_RECORD_BYTES = 1_000_000


class LockBusyError(RuntimeError):
    """Another process or thread is using this wiki; retry the operation later."""


class StaleBaseError(RuntimeError):
    """The candidate was prepared against a wiki that has since changed."""


class RecoveryError(UnsafePathError):
    """An interrupted transaction's evidence could not be trusted; nothing was changed and it was kept."""


_held = threading.local()


def _identity(wiki: Path) -> tuple[Path, str]:
    """(worktree Git administration directory, digest of the canonical Git/worktree/wiki identity)."""
    canonical = wiki.resolve()
    parent = canonical
    while not parent.exists():
        parent = parent.parent
    result = subprocess.run(
        ["git", "-C", str(parent), "rev-parse", "--absolute-git-dir", "--show-toplevel"],
        capture_output=True,
        text=True,
        check=True,
    )
    admin, root = result.stdout.splitlines()
    identity = json.dumps([str(Path(admin).resolve()), str(Path(root).resolve()), str(canonical)])
    return Path(admin).resolve(), hashlib.sha256(identity.encode()).hexdigest()


def _lock_path(wiki: Path) -> Path:
    admin, digest = _identity(wiki)
    return admin / f"repowiki-lock-{digest}"


@contextmanager
def wiki_lock(wiki: Path) -> Iterator[None]:
    """Nonblocking OS lock shared by publication, recovery and complete reads.

    Stored in worktree Git administration, never unlinked (which would split
    ownership across inodes). Nested calls in the owning thread reuse the lock.
    The kernel releases ownership on process termination, including SIGKILL.
    """
    path = _lock_path(wiki)
    held = getattr(_held, "locks", None)
    if held is None:
        held = _held.locks = {}
    key = (os.getpid(), path)
    if key in held:
        yield
        return
    fd = os.open(path, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    try:
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise LockBusyError("wiki is busy; retry after the current operation finishes") from exc
        held[key] = fd
        try:
            yield
        finally:
            del held[key]
    finally:
        os.close(fd)


def base_digest(wiki: Path) -> str:
    """Identity of every page and the index under the common lock, after recovery.

    Bound to the canonical worktree/wiki identity and built from page, index and
    ownership metadata (name, type, inode, size, modification and change times).
    No wiki file is opened, so unindexed or secret-pattern files are never read.
    Any write, replacement, deletion or ownership transition changes it.
    """
    from .ownership import record_path

    with wiki_lock(wiki):
        recover(wiki)
        digest = hashlib.sha256()
        digest.update(_identity(wiki)[1].encode())
        for path in sorted(wiki.iterdir()) if wiki.exists() else []:
            if path.name != INDEX and not path.name.endswith(".md"):
                continue
            info = path.lstat()  # never follows a symlink and never reads content
            meta = json.dumps(
                [path.name, info.st_mode, info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns]
            ).encode()
            digest.update(len(meta).to_bytes(8, "big") + meta)
        ownership = record_path(wiki)
        if os.path.lexists(ownership):
            info = ownership.lstat()
            meta = json.dumps(
                ["ownership", info.st_mode, info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns]
            ).encode()
            digest.update(len(meta).to_bytes(8, "big") + meta)
        return digest.hexdigest()


def check_base(wiki: Path, expected: str | None) -> None:
    """Caller holds wiki_lock through this check and publication."""
    if expected is not None and base_digest(wiki) != expected:
        raise StaleBaseError("wiki changed since candidate preparation; regenerate or update again")


def transact(wiki: Path, writes: dict[str, str], deletes: list[str], *, expected_base: str | None = None) -> None:
    with wiki_lock(wiki):
        recover(wiki)
        check_base(wiki, expected_base)
        _transact(wiki, writes, deletes)


def transaction_dir(wiki: Path) -> Path:
    """Authoritative transaction state for `wiki`: protected local Git administration, never the checkout."""
    admin, digest = _identity(wiki)
    return admin / TXN_ROOT / digest


def transaction_record(wiki: Path) -> Path:
    return transaction_dir(wiki) / RECORD


def _step(name: str) -> None:
    """A transaction transition (tests terminate the process here to check recovery at every point)."""


def _fsync_dir(path: Path) -> None:
    fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def _write_synced(path: Path, data: bytes) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    try:
        view = memoryview(data)
        while view:
            view = view[os.write(fd, view) :]
        os.fsync(fd)
    finally:
        os.close(fd)


def _durable_replace(path: Path, data: bytes) -> None:
    """Write `data` to a temp file, fsync it, rename it over `path`, fsync the directory."""
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
    _fsync_dir(path.parent)


def _real_dir(path: Path, *, create: bool = False) -> None:
    """`path` is a real directory (never a symlink); with `create`, make each missing level (mode 0700)
    and fsync its parent, so a new directory is durable before anything is written into it."""
    if create and not os.path.lexists(path):
        missing = []
        level = path
        while not os.path.lexists(level):
            missing.append(level)
            level = level.parent
        _real_dir(level)
        for new in reversed(missing):
            new.mkdir(mode=0o700)
            _fsync_dir(new.parent)
    info = path.lstat()
    if stat.S_ISLNK(info.st_mode) or not stat.S_ISDIR(info.st_mode):
        raise RecoveryError(f"{path} is not a plain directory; refusing to use it for a transaction")


def _sha(path: Path) -> str | None:
    """sha256 of a regular file's bytes, None if absent; a symlink or other file type refuses."""
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise RecoveryError(f"{path} is not a regular file ({exc}); refusing to touch it") from exc
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            raise RecoveryError(f"{path} is not a regular file; refusing to touch it")
        h = hashlib.sha256()
        while chunk := os.read(fd, 1 << 20):
            h.update(chunk)
        return h.hexdigest()
    finally:
        os.close(fd)


def _check_targets(writes: dict[str, str], deletes: list[str]) -> list[str]:
    """Every target once: a name written and deleted, deleted twice, or equal ignoring case refuses."""
    names = [*writes, *deletes]
    folded = [n.casefold() for n in names]
    if len(set(folded)) != len(folded):
        raise UnsafePathError("conflicting duplicate targets in one transaction; refusing to publish")
    return names


def _target(wiki: Path, name: str) -> Path:
    from .ownership import TARGET, _directory, record_path

    if name == TARGET:
        _directory(wiki)
        return record_path(wiki)
    # Publication validates names/types before staging; recovery validates names in the
    # journal and checks the target with _sha's no-follow regular-file guard. Preserve
    # RecoveryError for a target that became a symlink after publication was interrupted.
    return wiki / name


def _transact(
    wiki: Path,
    writes: dict[str, str],
    deletes: list[str],
    *,
    adopted: dict[str, str] | None = None,
    reviewed: dict[str, str] | None = None,
) -> None:
    """Replace, add and delete wiki files as one durable, recoverable transaction.

    The authoritative record and the staging directory live in worktree Git
    administration (`transaction_dir`), never in the checkout. Order:

    1. check exact ownership; stage every new file and the new ownership receipt
       (fsync each, then the staging directory);
    2. write the record, state "prepared", with the exact sha256 of every
       target before and after (fsync, rename, fsync directory);
    3. move each existing target into staging, then each new file into place;
       fsync the wiki, ownership and staging directories;
    4. rewrite the record with state "committed": this is the commit point;
    5. remove staging and the record.

    A failure before the commit point rolls back at once; a process killed at
    any point is finished (committed) or undone (prepared) by `recover`, which
    checks every hash before it changes anything.
    """
    from . import ownership

    recover(wiki)
    names = _check_targets(writes, deletes)
    wiki.mkdir(parents=True, exist_ok=True)
    for name in names:
        wiki_file(wiki, name)  # every target is checked before anything moves
    prior_pages = ownership.load(wiki)
    pages = ownership.checked_update(wiki, writes, deletes) if adopted is None else adopted
    ownership._directory(wiki, create=True)
    # The receipt moves through the same journal, backups, commit point and recovery as pages.
    payloads = {name: text.encode("utf-8") for name, text in writes.items()}
    payloads[ownership.TARGET] = ownership.encode(wiki, pages)
    if len(payloads[ownership.TARGET]) > ownership.MAX_OWNERSHIP_BYTES:
        raise UnsafePathError("too many files for one ownership record; nothing was changed")
    names.append(ownership.TARGET)
    txn = transaction_dir(wiki)
    _real_dir(txn, create=True)
    if os.stat(txn).st_dev != os.stat(wiki).st_dev:
        raise UnsafePathError("Git administration and the wiki directory must be on one filesystem")
    stage = txn / STAGE
    if os.path.lexists(stage) or os.path.lexists(txn / RECORD):
        raise RecoveryError(f"an unrecovered transaction remains in {txn}; refusing to start another")
    stage.mkdir(mode=0o700)
    _fsync_dir(txn)
    entries: list[dict[str, object]] = []
    journal: dict[str, object] = {
        "version": 2,
        "wiki": str(wiki.resolve()),
        "state": "prepared",
        "entries": entries,
        "reviewed": reviewed or {},
    }
    try:
        for name in names:
            new = None
            if name in payloads:
                data = payloads[name]
                _write_synced(stage / f"new-{name}", data)
                new = hashlib.sha256(data).hexdigest()
            old = _sha(_target(wiki, name))
            if name not in (INDEX, ownership.TARGET) and old is not None and old != prior_pages.get(name):
                raise ownership.OwnershipError(f"{name}: page bytes changed before staging; refusing replacement")
            entries.append({"name": name, "existed": old is not None, "old": old, "new": new})
        record = json.dumps(journal).encode()
        committed = json.dumps({**journal, "state": "committed"}).encode()
        if max(len(record), len(committed)) > MAX_RECORD_BYTES:  # both records must stay loadable
            raise UnsafePathError("too many files for one transaction; nothing was changed")
        _fsync_dir(stage)
        _step("staged")
        _durable_replace(txn / RECORD, record)
        _step("prepared")
    except BaseException:
        _cleanup(wiki, stage)  # nothing in the wiki has moved yet
        raise
    try:
        # Recheck after staging: a writer outside the shared lock must not silently lose its bytes.
        for entry in entries:
            if _sha(_target(wiki, str(entry["name"]))) != entry["old"]:
                raise StaleBaseError("wiki changed during transaction preparation; refusing replacement")
        for name, digest in (reviewed or {}).items():
            if _sha(wiki_file(wiki, name)) != digest:
                raise StaleBaseError("reviewed adoption bytes changed during transaction preparation")
        for entry in entries:
            name = str(entry["name"])
            target = _target(wiki, name)
            if _sha(target) != entry["old"]:
                raise StaleBaseError(f"{name}: bytes changed before replacement")
            if entry["existed"]:
                os.replace(target, stage / f"old-{name}")
                _fsync_dir(stage)  # the original is durably kept before anything replaces it
                _fsync_dir(target.parent)
                _step(f"moved-old:{name}")
            if entry["new"] is not None:
                os.replace(stage / f"new-{name}", target)
                _fsync_dir(target.parent)
                _fsync_dir(stage)
                _step(f"moved-new:{name}")
        _step("synced")
        journal["state"] = "committed"
        _durable_replace(txn / RECORD, json.dumps(journal).encode())  # the commit point
        _step("committed")
    except BaseException:
        # Decide from the record on disk, never from how far this process thinks it got: once the
        # committed record exists, the transaction is only ever finished, never rolled back. A record
        # that cannot be read is left untouched for recovery, which refuses it.
        state = _recorded_state(wiki)
        if state == "committed":
            _finish(wiki, journal)
        elif state == "prepared":
            _rollback(wiki, journal)
        raise
    _finish(wiki, journal)
    _step("cleaned")


def _recorded_state(wiki: Path) -> str | None:
    try:
        return str(_load_record(wiki, transaction_record(wiki))["state"])
    except RecoveryError:
        return None


def _finish(wiki: Path, journal: dict[str, object]) -> None:
    """Complete a committed transaction: every target must hold exactly its new bytes (or be gone)
    before the kept originals are removed; any mismatch changes nothing and keeps the evidence."""
    stage = transaction_dir(wiki) / STAGE
    for entry in journal["entries"]:  # type: ignore[union-attr]
        name = str(entry["name"])
        kept = stage / f"old-{name}"
        if _sha(_target(wiki, name)) != entry["new"] or (os.path.lexists(kept) and _sha(kept) != entry["old"]):
            raise RecoveryError(f"{name}: committed transaction evidence does not match; nothing was changed")
    for name, digest in journal.get("reviewed", {}).items():  # type: ignore[union-attr]
        if _sha(wiki_file(wiki, name)) != digest:
            raise RecoveryError("reviewed adoption bytes changed; transaction evidence kept")
    _cleanup(wiki, stage)


def _rollback(wiki: Path, journal: dict[str, object]) -> None:
    """Undo a prepared transaction. Every hash is checked first; any mismatch changes nothing."""
    stage = transaction_dir(wiki) / STAGE
    actions: list[tuple[Path, Path | None]] = []  # (source, destination); destination None = unlink source
    for entry in journal["entries"]:  # type: ignore[union-attr]
        name = str(entry["name"])
        target, kept = _target(wiki, name), stage / f"old-{name}"
        current = _sha(target)
        if os.path.lexists(kept):
            if _sha(kept) != entry["old"] or current not in (None, entry["new"]):
                raise RecoveryError(f"{name}: transaction evidence does not match; nothing was changed")
            actions.append((kept, target))
        elif entry["existed"]:
            if current != entry["old"]:
                raise RecoveryError(f"{name}: transaction evidence does not match; nothing was changed")
        elif current is not None:
            if current != entry["new"]:
                raise RecoveryError(f"{name}: not the file this transaction added; nothing was changed")
            actions.append((target, None))
    for source, destination in actions:
        if destination is None:
            source.unlink()
            _fsync_dir(source.parent)
            _step(f"rolled-back:{source.name}")
        else:
            os.replace(source, destination)  # the original comes back, over this transaction's new file
            _fsync_dir(destination.parent)
            _fsync_dir(stage)
            _step(f"rolled-back:{destination.name}")
    _cleanup(wiki, stage)


def _cleanup(wiki: Path, txn: Path) -> None:
    """Remove the staging directory `txn` and the record (Git administration only, never the checkout)."""
    root = transaction_dir(wiki)
    if txn == root / STAGE and os.path.lexists(txn):
        _real_dir(txn)
        shutil.rmtree(txn)  # staging first: a record without staging is still recoverable evidence
        _fsync_dir(root)
        _step("cleanup:staging")
    (root / RECORD).unlink(missing_ok=True)
    if root.is_dir() and not root.is_symlink():
        _fsync_dir(root)


def _load_record(wiki: Path, path: Path) -> dict[str, object]:
    """The record, fully validated; anything malformed raises RecoveryError and is kept for inspection."""
    from .ownership import TARGET, _unique

    def bad(why: str) -> RecoveryError:
        return RecoveryError(f"untrusted transaction record {path}: {why}; nothing was changed")

    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    except OSError as exc:
        raise bad(f"cannot open it ({exc})") from exc
    with os.fdopen(fd, "rb") as fh:
        if not stat.S_ISREG(os.fstat(fh.fileno()).st_mode):
            raise bad("not a regular file")
        raw = fh.read(MAX_RECORD_BYTES + 1)
    if len(raw) > MAX_RECORD_BYTES:
        raise bad("too large")
    try:
        data = json.loads(raw, object_pairs_hook=_unique)
    except ValueError as exc:
        raise bad("not JSON") from exc
    if (
        not isinstance(data, dict)
        or type(data.get("version")) is not int
        or data["version"] not in (1, 2)
        or set(data) != ({"version", "wiki", "state", "entries"} | ({"reviewed"} if data["version"] == 2 else set()))
    ):
        raise bad("unknown schema")
    if data["wiki"] != str(wiki.resolve()):
        raise bad("it belongs to another wiki directory")
    if data["state"] not in ("prepared", "committed") or not isinstance(data["entries"], list):
        raise bad("unknown state")
    seen: set[str] = set()
    for entry in data["entries"]:
        if not isinstance(entry, dict) or set(entry) != {"name", "existed", "old", "new"}:
            raise bad("malformed entry")
        name = entry["name"]
        if (
            not (name == INDEX or safe_page_file(name) or (data["version"] == 2 and name == TARGET))
            or name.casefold() in seen
        ):
            raise bad("unsafe or duplicate target")
        seen.add(name.casefold())
        if not isinstance(entry["existed"], bool):
            raise bad("malformed entry")
        old, new = entry["old"], entry["new"]
        if entry["existed"]:
            if not (isinstance(old, str) and _HEX64.fullmatch(old)):
                raise bad("malformed hash")
        elif old is not None:
            raise bad("malformed hash")
        if new is not None and not (isinstance(new, str) and _HEX64.fullmatch(new)):
            raise bad("malformed hash")
        if name == TARGET and new is None:
            raise bad("missing new ownership")
    if data["version"] == 2:
        if TARGET not in seen or not isinstance(data["reviewed"], dict):
            raise bad("missing ownership or review evidence")
        for name, digest in data["reviewed"].items():
            if not safe_page_file(name) or not isinstance(digest, str) or not _HEX64.fullmatch(digest):
                raise bad("unsafe reviewed page or hash")
    return data


def recover(wiki: Path) -> bool:
    """Recover only while owning the same OS lock as the publisher."""
    with wiki_lock(wiki):
        return _recover(wiki)


def _recover(wiki: Path) -> bool:
    """Finish (committed) or undo (prepared) an interrupted publish. Returns True if one was found.

    Only the record in Git administration is evidence; a journal file in the checkout is ignored.
    Recovering again afterwards finds nothing and changes nothing.
    """
    txn = transaction_dir(wiki)
    if not os.path.lexists(txn):
        return False
    _real_dir(txn)
    record, stage = txn / RECORD, txn / STAGE
    if not os.path.lexists(record):
        if not os.path.lexists(stage):
            return False
        _cleanup(wiki, stage)  # killed before the record existed: nothing in the wiki moved
        return True
    journal = _load_record(wiki, record)
    if os.path.lexists(stage):
        _real_dir(stage)
    if journal["state"] == "committed":
        _finish(wiki, journal)
    else:
        _rollback(wiki, journal)
    return True
