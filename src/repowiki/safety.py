"""Filesystem guard rails.

repowiki only ever writes and deletes inside the wiki directory, only through
plain file names (never paths), never through symlinks, and only deletes pages
that carry the marker repowiki itself writes into every page.
"""

from __future__ import annotations

import json
import fcntl
import hashlib
import subprocess
import threading
from contextlib import contextmanager
from collections.abc import Iterator
import os
import re
import shutil
import tempfile
from pathlib import Path

INDEX = "index.json"
PAGE_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*\.md$")
# Written at the end of every generated page; only pages carrying it are ever deleted.
GENERATED_MARK = "<!-- generated by repowiki -->"


class UnsafePathError(ValueError):
    """A path would take a read, write or delete outside the wiki directory."""


def safe_page_file(value: object) -> bool:
    return isinstance(value, str) and bool(PAGE_NAME_RE.match(value))


def check_wiki_dir(wiki_dir: str) -> str:
    """Normalised repo-relative wiki directory; rejects absolute paths, ``..`` and ``.git``."""
    raw = str(wiki_dir).strip()
    if not raw or raw.startswith(("/", "\\", "~")) or re.match(r"^[A-Za-z]:", raw) or "\\" in raw:
        raise UnsafePathError(f"wiki_dir must be a relative path inside the repository, got {wiki_dir!r}")
    parts = [p for p in raw.split("/") if p not in ("", ".")]
    if not parts or ".." in parts:
        raise UnsafePathError(f"wiki_dir must stay inside the repository, got {wiki_dir!r}")
    if parts[0] == ".git":
        raise UnsafePathError("wiki_dir cannot be inside .git")
    return "/".join(parts)


def wiki_path(root: Path, wiki_dir: str) -> Path:
    """``root/wiki_dir``, refusing any symlinked component that leads outside ``root``."""
    rel = check_wiki_dir(wiki_dir)
    path = root / rel
    real_root = root.resolve()
    real = path.resolve()
    if real != real_root and real_root not in real.parents:
        raise UnsafePathError(f"{rel} resolves outside the repository ({real}); refusing to use it")
    if real == real_root:
        raise UnsafePathError(f"{rel} resolves to the repository root; refusing to use it")
    return path


def wiki_file(wiki: Path, name: str) -> Path:
    """A page or index file directly inside ``wiki``; never a symlink or a directory."""
    if name != INDEX and not safe_page_file(name):
        raise UnsafePathError(f"not a plain page file name: {name!r}")
    path = wiki / name
    if path.is_symlink():
        raise UnsafePathError(f"{path} is a symlink; refusing to read or write through it")
    if path.exists() and not path.is_file():
        raise UnsafePathError(f"{path} is not a regular file")
    return path


def read_wiki_file(wiki: Path, name: str) -> str | None:
    path = wiki_file(wiki, name)
    return path.read_text(encoding="utf-8") if path.is_file() else None


def atomic_write(path: Path, text: str) -> None:
    """Write via a temp file in the same directory and ``os.replace`` it into place."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def generated_by_repowiki(path: Path) -> bool:
    """True only for a regular, non-symlink file that carries repowiki's page marker."""
    if path.is_symlink() or not path.is_file():
        return False
    try:
        return GENERATED_MARK in path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False


# --------------------------------------------------------------------------- transactional publish

JOURNAL = ".repowiki-journal.json"


class LockBusyError(RuntimeError):
    """Another process or thread is using this wiki; retry the operation later."""


class StaleBaseError(RuntimeError):
    """The candidate was prepared against a wiki that has since changed."""


_held = threading.local()


def _lock_path(wiki: Path) -> Path:
    canonical = wiki.resolve()
    parent = canonical
    while not parent.exists():
        parent = parent.parent
    result = subprocess.run(
        ["git", "-C", str(parent), "rev-parse", "--absolute-git-dir", "--show-toplevel"],
        capture_output=True, text=True, check=True,
    )
    admin, root = result.stdout.splitlines()
    identity = json.dumps([str(Path(admin).resolve()), str(Path(root).resolve()), str(canonical)])
    digest = hashlib.sha256(identity.encode()).hexdigest()
    return Path(admin).resolve() / f"repowiki-lock-{digest}"


@contextmanager
def wiki_lock(wiki: Path) -> Iterator[None]:
    """Nonblocking OS lock shared by publication, recovery and complete reads.

    Stored in worktree Git administration, never unlinked (which would split
    ownership across inodes). Nested calls in the owning thread reuse the lock.
    The kernel releases ownership on process termination, including SIGKILL.
    """
    path = _lock_path(wiki)
    held = getattr(_held, "locks", None)
    if held is None:
        held = _held.locks = {}
    key = (os.getpid(), path)
    if key in held:
        yield
        return
    fd = os.open(path, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    try:
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise LockBusyError("wiki is busy; retry after the current operation finishes") from exc
        held[key] = fd
        try:
            yield
        finally:
            del held[key]
    finally:
        os.close(fd)


def base_digest(wiki: Path) -> str:
    """Digest every page and the index under the common lock, after recovery."""
    with wiki_lock(wiki):
        recover(wiki)
        digest = hashlib.sha256()
        for path in sorted(wiki.iterdir()) if wiki.exists() else []:
            if path.name != INDEX and not path.name.endswith(".md"):
                continue
            # Never follow page symlinks, including while checking a stale base.
            if path.is_symlink():
                content = b"link:" + os.readlink(path).encode()
            elif path.is_file():
                content = b"file:" + path.read_bytes()
            else:
                content = b"non-file"
            name = path.name.encode()
            digest.update(len(name).to_bytes(8, "big") + name)
            digest.update(len(content).to_bytes(8, "big") + content)
        return digest.hexdigest()


def check_base(wiki: Path, expected: str | None) -> None:
    """Caller holds wiki_lock through this check and publication."""
    if expected is not None and base_digest(wiki) != expected:
        raise StaleBaseError("wiki changed since candidate preparation; regenerate or update again")


def transact(
    wiki: Path, writes: dict[str, str], deletes: list[str], *, expected_base: str | None = None
) -> None:
    with wiki_lock(wiki):
        recover(wiki)
        check_base(wiki, expected_base)
        _transact(wiki, writes, deletes)


def _transact(wiki: Path, writes: dict[str, str], deletes: list[str]) -> None:
    """Replace, add and delete wiki files as one recoverable transaction.

    New files are staged in a private directory inside `wiki`, and a journal
    records which targets existed. Each existing target is moved into the
    staging directory before its replacement is moved in. On any error the
    journal is rolled back at once; if the process dies, `recover` rolls it
    back on the next run. Either every change lands, or none does.
    """
    recover(wiki)
    wiki.mkdir(parents=True, exist_ok=True)
    names = list(dict.fromkeys([*writes, *deletes]))
    for name in names:
        wiki_file(wiki, name)  # every target is checked before anything moves
    txn = Path(tempfile.mkdtemp(prefix=".repowiki-txn-", dir=wiki))
    existed = {n: (wiki / n).exists() for n in names}
    journal: dict[str, object] = {"txn": txn.name, "existed": existed, "committed": False}
    try:
        for name, text in writes.items():
            with open(txn / f"new-{name}", "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
        atomic_write(wiki / JOURNAL, json.dumps(journal))
    except BaseException:
        _cleanup(wiki, txn)  # nothing in the wiki has moved yet
        raise
    try:
        for name in names:
            if existed[name]:
                os.replace(wiki / name, txn / f"old-{name}")
            if name in writes:
                os.replace(txn / f"new-{name}", wiki / name)
        journal["committed"] = True
        atomic_write(wiki / JOURNAL, json.dumps(journal))
    except BaseException:
        _rollback(wiki, journal)
        raise
    _cleanup(wiki, txn)


def _rollback(wiki: Path, journal: dict[str, object]) -> None:
    txn = wiki / str(journal["txn"])
    existed = journal.get("existed")
    for name, was_there in (existed if isinstance(existed, dict) else {}).items():
        if not safe_page_file(name) and name != INDEX:
            continue
        old = txn / f"old-{name}"
        if old.exists():
            os.replace(old, wiki / name)  # the original comes back, over any new file
        elif not was_there:
            (wiki / name).unlink(missing_ok=True)  # a file this transaction added
    _cleanup(wiki, txn)


def _cleanup(wiki: Path, txn: Path) -> None:
    if txn.name.startswith(".repowiki-txn-") and txn.parent == wiki and not txn.is_symlink():
        shutil.rmtree(txn, ignore_errors=True)
    (wiki / JOURNAL).unlink(missing_ok=True)


def recover(wiki: Path) -> bool:
    """Recover only while owning the same OS lock as the publisher."""
    with wiki_lock(wiki):
        return _recover(wiki)


def _recover(wiki: Path) -> bool:
    """Finish or undo a publish that was interrupted. Returns True if one was found."""
    path = wiki / JOURNAL
    if path.is_symlink() or not path.is_file():
        return False
    try:
        journal = json.loads(path.read_text(encoding="utf-8"))
        txn = str(journal["txn"])
    except (OSError, ValueError, KeyError, TypeError):
        path.unlink()
        return True
    if not re.fullmatch(r"\.repowiki-txn-[A-Za-z0-9_]+", txn):
        path.unlink()
        return True
    if journal.get("committed"):
        _cleanup(wiki, wiki / txn)
    else:
        _rollback(wiki, journal)
    return True
